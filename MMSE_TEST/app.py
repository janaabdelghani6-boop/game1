import streamlit as st

# تعريف الأسئلة والدرجات
questions = {
    "ما هو اليوم؟": ["الإثنين", "الثلاثاء", "الأربعاء", "الخميس"],
    "في أي مدينة أنت؟": ["القاهرة", "الإسكندرية", "الجيزة", "بورسعيد"],
    "كرر الكلمات التالية: تفاحة - طاولة - كلب": ["تم التذكر", "لم يتم التذكر"],
    "ما هو 100 - 7؟": ["93", "94", "95", "90"],
    "ارسم ساعة تشير إلى 11:10": ["تم التنفيذ", "لم يتم التنفيذ"]
}

# تهيئة التطبيق
st.title("اختبار MMSE لتقييم المراحل المبكرة لمرض الزهايمر")

# جمع إجابات المستخدم
score = 0
for question, options in questions.items():
    answer = st.radio(question, options)
    if answer == options[0]:  # اعتبر أول اختيار هو الصحيح
        score += 1

# حساب النتيجة وعرض التشخيص
if st.button("عرض النتيجة"):
    st.write(f"درجتك: {score} من {len(questions)}")

    if score >= 4:
        st.success("نتيجتك طبيعية، لا يوجد مشاكل في الإدراك.")
    elif score == 3:
        st.warning("قد يكون لديك ضعف إدراكي خفيف، يفضل المتابعة مع طبيب.")
    else:
        st.error("النتيجة تشير إلى احتمال وجود مرض الزهايمر، يُنصح باستشارة طبيب مختص.")
